    # שונה: הורחב משמעותית — הרשימה המקורית הייתה קצרה מדי ופספסה מילים נפוצות מאוד
    # כל קטגוריה מסומנת כדי להקל על תחזוקה עתידית
    STOP_WORDS = {

        # --- conjunctions & connectors ---
        'ו', 'או', 'אבל', 'כי', 'אם', 'אז', 'גם', 'רק', 'אף', 'אך',
        'בכן', 'לכן', 'לפיכך', 'אולם', 'ברם', 'אלא', 'אלו', 'כאשר',
        'כש', 'בעוד', 'בזמן', 'מאחר', 'הגם', 'מכיוון', 'כיוון',

        # --- prepositions ---
        'של', 'על', 'אל', 'מן', 'עם', 'בין', 'לפני', 'אחרי', 'תחת',
        'מול', 'סביב', 'לאחר', 'לפי', 'בגלל', 'למרות', 'בלי', 'ללא',
        'עד', 'מעל', 'מתחת', 'מאחורי', 'לעבר', 'כלפי', 'נגד', 'דרך',
        'תוך', 'בתוך', 'מבין', 'מאת', 'לצד', 'בצד',

        # --- prefixed prepositions (single letters that Stanza may return as lemmas) ---
        'ב', 'ל', 'מ', 'כ', 'ש', 'ה',

        # --- personal pronouns ---
        'אני', 'אתה', 'את', 'הוא', 'היא', 'אנחנו', 'אנו',
        'אתם', 'אתן', 'הם', 'הן',

        # --- possessive suffixes as standalone lemmas ---
        'שלי', 'שלך', 'שלו', 'שלה', 'שלנו', 'שלכם', 'שלהם', 'שלהן',

        # --- demonstratives & interrogatives ---
        'זה', 'זו', 'זאת', 'אלה', 'אלו', 'הנה', 'הרי',
        'מה', 'מי', 'איך', 'למה', 'מדוע', 'היכן', 'איפה', 'מתי',
        'כיצד', 'כמה', 'האם', 'הכי',

        # --- common adverbs & particles ---
        'כל', 'כבר', 'עוד', 'פה', 'שם', 'כן', 'לא', 'יש', 'אין',
        'מאוד', 'יותר', 'פחות', 'כך', 'ככה', 'כאן', 'שוב', 'בכלל',
        'בדיוק', 'ממש', 'רגע', 'פעם', 'תמיד', 'לעולם', 'אולי',
        'בטח', 'בוודאי', 'כנראה', 'אחרת', 'אחר', 'אחרי', 'כבר',
        'עדיין', 'כמו', 'כן', 'לעצמ', 'יחד', 'ביחד', 'הכל',

        # --- articles & determiners ---
        'כל', 'כלל', 'כולם', 'כולן', 'כולנו', 'אותו', 'אותה',
        'אותם', 'אותן', 'אותי', 'אותך', 'אותנו',

        # --- existential & copular ---
        'היה', 'הייה', 'היו', 'יהיה', 'יהיו', 'להיות',

        # --- common filler words in song lyrics ---
        'הו', 'אה', 'אהה', 'אוה', 'נא', 'נו', 'הי', 'הא', 'אוי', 'אוי',
        'לה', 'לי', 'לו', 'לה', 'ום', 'ופ',
    }

    # POS tags that are never content words — filtered regardless of lemma
    UNWANTED_POS = {
        'PUNCT',  # punctuation
        'NUM',  # numbers
        'ADP',  # prepositions / postpositions
        'CCONJ',  # coordinating conjunctions
        'SCONJ',  # subordinating conjunctions
        'DET',  # determiners (ה' הידיעה)
        'PRON',  # pronouns
        'AUX',  # שונה: נוסף — פועל עזר (היה, יהיה) לא נושא מידע סיווגי
        'INTJ',  # שונה: נוסף — קריאות (הו, אה) שמופיעות הרבה בשירים
        'PART',  # שונה: נוסף — חלקיקים (לא, גם) שStanza מתייג כPART
        'X',  # שונה: נוסף — מילים לא מזוהות / זרות / רעש
    }

    def is_valid(self, lemma: str, upos: str) -> bool:
        if upos in self.UNWANTED_POS:
            return False
        if lemma in self.STOP_WORDS:
            return False
        # שונה: הורחב הסף המינימלי מ-2 ל-2 אותיות — נשאר אותו דבר אבל
        # נוסף: מסנן מילה שמורכבת רק מאות אחת אחרי חיתוך תחיליות
        if len(lemma) < 2:
            return False
        return True